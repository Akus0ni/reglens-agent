"""`evals/results.md` from the run files, the judge scores and the hand check (spec 0002, R2.10)."""

import statistics
from pathlib import Path
from typing import Any

from reglens_agent.evals.judge import HAND_CHECK, JUDGE_MODEL, read_labels
from reglens_agent.evals.runner import merged_runs
from reglens_agent.pricing import cost_usd

RESULTS = Path("evals/results.md")
CHECK_NAMES = ("completed", "guards", "searched", "verified", "quiet", "required", "severity")


def write_report(run_paths: list[Path]) -> Path:
    runs = merged_runs(run_paths)
    first = runs[0]
    sources = "; ".join(f"run {r['run']}: {', '.join(f'`{f}`' for f in r['files'])} (commits "
                        f"{', '.join(f'`{c}`' for c in r['commits'])})" for r in runs)
    lines = ["# reglens-agent eval results", "",
             f"Generated by `reglens-agent eval report`. Sources: {sources}. A later file's scenario replaces an "
             f"earlier one in the same run (a re-record). Scenarios: `evals/scenarios.json` (15: 13 in scope, 2 out "
             f"of scope). Models: {', '.join(first['models'])}; judge `{JUDGE_MODEL}`. Each run is one review per "
             f"scenario, to the approval step.",
             "", "## Checks (scenarios passing / applicable)", "",
             "| Check | " + " | ".join(f"run {r['run']}" for r in runs) + " |",
             "|-------|" + "|".join("---" for _ in runs) + "|"]
    lines += [f"| {name} | " + " | ".join(r["summary"]["passed"][name] for r in runs) + " |" for name in CHECK_NAMES]

    lines += ["", "## Per scenario", "", "✓ pass, ✗ fail, – not applicable. Failing checks are named with their detail below.",
              "", "| Scenario | " + " | ".join(f"run {r['run']}" for r in runs) + " | Findings (run 1) |",
              "|----------|" + "|".join("---" for _ in runs) + "|---|"]
    unstable, details = [], []
    for scenario_id, result in first["scenarios"].items():
        marks = []
        for run in runs:
            checks = run["scenarios"][scenario_id]["checks"]
            marks.append("".join("✓" if checks[n]["passed"] else ("–" if checks[n]["passed"] is None else "✗")
                                 for n in CHECK_NAMES))
            details += [f"- run {run['run']} {scenario_id}: {n}: {checks[n]['detail']}" for n in CHECK_NAMES
                        if checks[n]["passed"] is False]
        if len(set(marks)) > 1:
            unstable.append(scenario_id)
        severities = [f["severity"] for f in result["state"].get("findings", [])]
        lines.append(f"| {scenario_id} | " + " | ".join(f"`{m}`" for m in marks) +
                     f" | {len(severities)} ({', '.join(severities) or 'none'}) |")
    lines += ["", f"Column order: {', '.join(CHECK_NAMES)}."]
    if details:
        lines += ["", "Failures:", ""] + details
    lines += ["", f"**Spread:** {len(unstable)} of {len(first['scenarios'])} scenarios had different check results "
              f"between runs" + (f" ({', '.join(unstable)})" if unstable else "") + "."]

    scores = [s["judge"] for r in runs for s in r["scenarios"].values() if "judge" in s]
    if scores:
        lines += ["", "## Judge", "",
                  f"`{JUDGE_MODEL}`, n = {len(scores)} memos: grounded mean "
                  f"{statistics.mean(s['grounded'] for s in scores):.2f}, actionable mean "
                  f"{statistics.mean(s['actionable'] for s in scores):.2f}.",
                  f"Grounded distribution: {_distribution(s['grounded'] for s in scores)}; "
                  f"actionable: {_distribution(s['actionable'] for s in scores)}."]
        lines += _hand_check(first)

    lines += ["", "## Cost and time", "", "| Run | Reviews | Cost | Per review | p50 wall time |",
              "|-----|---------|------|------------|---------------|"]
    for run in runs:
        summary = run["summary"]
        lines.append(f"| {run['run']} | {len(run['scenarios'])} | ${summary['cost_usd']:.4f} | "
                     f"${summary['cost_per_review_usd']:.4f} | {summary['p50_seconds']} s |")
    if scores:
        judge_cost = sum(cost_usd(r["judge_usage"]) for r in runs)
        lines.append(f"\nJudge: ${judge_cost:.4f} for {len(scores)} memos.")
    RESULTS.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return RESULTS


def _hand_check(run: dict[str, Any]) -> list[str]:
    if not HAND_CHECK.exists():
        return []
    labels = read_labels()
    pairs = [(labels[s][c], run["scenarios"][s]["judge"][c]) for s in labels if "judge" in run["scenarios"].get(s, {})
             for c in ("grounded", "actionable")]
    if not pairs:
        return ["", "Hand check: no labels yet."]
    within = sum(1 for a, b in pairs if abs(a - b) <= 1)
    exact = sum(1 for a, b in pairs if a == b)
    return ["", f"**Hand check** (D14: labelled by Claude in the working session, no API call; a second-model check, "
            f"not a human one): {len(labels)} memos × 2 criteria = {len(pairs)} judgements; within 1 point "
            f"{within}/{len(pairs)}, exact {exact}/{len(pairs)}. Sheet: `evals/hand-check.md`."]


def _distribution(values: Any) -> str:
    counts = {score: 0 for score in range(1, 6)}
    for value in values:
        counts[value] += 1
    return ", ".join(f"{score}: {n}" for score, n in counts.items() if n)
